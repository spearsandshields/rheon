#[test]
fn rounding_to_a_scale_is_one_step() {
  // DMN 1.6 Table 77: "Return n with given scale and rounding mode"; footnote 1: "Scale is in
  // the range [−6111..6176]". Every scale of that range is valid for every number, a zero and a
  // tiny number included, and the result is rounded once at the scale.
  let mut wrong = vec![];
  for (n, scale, results) in ROUNDED {
    let expected: Vec<&str> = if *results == "=" { vec![n; 7] } else { results.split(' ').collect() };
    for (mode, expected) in expected.iter().enumerate() {
      let actual = n.parse::<FeelNumber>().unwrap().round_to(*scale, MODES[mode]).ok();
      if actual != Some(expected.parse().unwrap()) {
        wrong.push(format!("{:?} of ({n}, {scale}): {actual:?}, expected {expected}", MODES[mode]));
      }
    }
  }
  assert!(wrong.is_empty(), "{} wrong results, the first: {:#?}", wrong.len(), &wrong[..wrong.len().min(12)]);
}
